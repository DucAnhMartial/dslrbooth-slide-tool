import { describe, expect, it } from 'vitest';
import fs from 'node:fs';
import path from 'node:path';
import {
  REGISTRATIONS_VIEW_COLUMNS,
  REGISTRATIONS_INNER_SELECT,
  NAME_SOURCE_VALUES,
  DEFAULT_VIEW_DEFINER,
  createRegistrationsViewDdl,
  createNameAuditViewDdl,
} from '../src/ops/registrationsViewSql';

/**
 * Locks the committed migration .sql to the module that generates it, and the
 * module's six-column contract to dbPoller.ts's untouchable (D-02) query
 * text. Following status-vocabulary.test.ts's "derive the array and the type
 * from one declaration" style: every assertion below reads the real exported
 * arrays/functions rather than copying their expected contents inline, so a
 * later drift shows up here instead of silently diverging.
 */

// Same normalisation on both sides: trailing whitespace on each line and a
// trailing-newline-at-EOF difference must not fail the drift guard, but any
// content difference must.
function normalise(text: string): string {
  return text
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => line.replace(/[ \t]+$/, ''))
    .join('\n')
    .replace(/\n+$/, '');
}

function buildExpectedMigrationText(): string {
  const header = `-- Phase 6: Ingestion Cutover
-- Generated by src/ops/verifyRegistrationsView.ts --emit-sql
-- from src/ops/registrationsViewSql.ts. Do not hand-edit this file — a
-- drift test (test/registrations-view-sql.test.ts) asserts it stays equal
-- to the module's emitted text. Regenerate instead:
--   npx ts-node src/ops/verifyRegistrationsView.ts --emit-sql

`;
  return `${header}${createRegistrationsViewDdl(DEFAULT_VIEW_DEFINER)}\n\n${createNameAuditViewDdl(DEFAULT_VIEW_DEFINER)}\n`;
}

const MIGRATION_SQL_PATH = path.resolve(__dirname, '../docs/migrations/06-registrations-view.sql');
const DB_POLLER_SOURCE_PATH = path.resolve(__dirname, '../src/ingestion/dbPoller.ts');

describe('registrationsViewSql — committed DDL matches the module (drift guard)', () => {
  it('the committed .sql equals, byte for byte after normalising whitespace, the module\'s emitted text', () => {
    const committed = normalise(fs.readFileSync(MIGRATION_SQL_PATH, 'utf8'));
    const expected = normalise(buildExpectedMigrationText());
    expect(committed).toBe(expected);
  });

  it('is load-bearing, not vacuous: a mutated definer (constructed in memory, committed file untouched) does NOT equal the committed .sql', () => {
    const committed = normalise(fs.readFileSync(MIGRATION_SQL_PATH, 'utf8'));
    const mutatedDefiner = `'someone-else'@'%'`;
    const mutatedText = normalise(
      `${createRegistrationsViewDdl(mutatedDefiner)}\n\n${createNameAuditViewDdl(mutatedDefiner)}\n`
    );
    expect(mutatedText).not.toBe(committed);
  });

  it('is load-bearing, not vacuous: dropping one column from the outer projection (constructed in memory) does NOT equal the committed .sql', () => {
    const committed = normalise(fs.readFileSync(MIGRATION_SQL_PATH, 'utf8'));
    const droppedColumnDdl = createRegistrationsViewDdl(DEFAULT_VIEW_DEFINER).replace(
      'SELECT d.id, d.name, d.email, d.phone, d.mode, d.registered_at',
      'SELECT d.id, d.name, d.email, d.phone, d.mode'
    );
    expect(droppedColumnDdl).not.toEqual(createRegistrationsViewDdl(DEFAULT_VIEW_DEFINER));
    expect(normalise(droppedColumnDdl)).not.toBe(committed);
  });
});

describe('registrationsViewSql — six-column contract with dbPoller.ts', () => {
  it('REGISTRATIONS_VIEW_COLUMNS joined with ", " appears verbatim inside dbPoller.ts\'s source text, in order', () => {
    const source = fs.readFileSync(DB_POLLER_SOURCE_PATH, 'utf8');
    const joined = REGISTRATIONS_VIEW_COLUMNS.join(', ');
    expect(source.includes(joined)).toBe(true);
  });

  it('the six-column DDL\'s outer SELECT projects exactly REGISTRATIONS_VIEW_COLUMNS and does not project name_source', () => {
    const ddl = createRegistrationsViewDdl(DEFAULT_VIEW_DEFINER);
    const outerSelectLine = ddl.split('\n').find((line) => line.trim().startsWith('SELECT d.'));
    expect(outerSelectLine).toBeDefined();
    const projected = (outerSelectLine as string)
      .replace('SELECT', '')
      .split(',')
      .map((col) => col.trim().replace(/^d\./, ''));
    expect(projected).toEqual([...REGISTRATIONS_VIEW_COLUMNS]);
    expect(projected).not.toContain('name_source');
  });

  it('the audit DDL\'s outer SELECT projects name_source (and not the full six-column set)', () => {
    const auditDdl = createNameAuditViewDdl(DEFAULT_VIEW_DEFINER);
    const outerSelectLine = auditDdl.split('\n').find((line) => line.trim().startsWith('SELECT d.'));
    expect(outerSelectLine).toBeDefined();
    const projected = (outerSelectLine as string)
      .replace('SELECT', '')
      .split(',')
      .map((col) => col.trim().replace(/^d\./, ''));
    expect(projected).toContain('name_source');
    expect(projected).toEqual(['id', 'name_source', 'registered_at']);
  });
});

describe('registrationsViewSql — NAME_SOURCE_VALUES matches the CASE expression', () => {
  it('has exactly five entries', () => {
    expect(NAME_SOURCE_VALUES.length).toBe(5);
  });

  it('every NAME_SOURCE_VALUES literal appears as a quoted literal inside REGISTRATIONS_INNER_SELECT\'s CASE expression', () => {
    for (const value of NAME_SOURCE_VALUES) {
      expect(REGISTRATIONS_INNER_SELECT.includes(`'${value}'`)).toBe(true);
    }
  });
});
